import { createHash } from 'node:crypto';
import { mkdir, readFile, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { LOCALES, PAGES, ROUTES, SITE } from '../site/content.mjs';
import { renderPage } from '../site/render.mjs';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicRoot = path.join(projectRoot, 'public');
const checkOnly = process.argv.includes('--check');
const pageTypes = Object.keys(ROUTES);
const localeKeys = Object.keys(LOCALES);
const assetVersion = SITE.assetVersion;

function outputPath(pathname) {
    if (pathname === '/') return path.join(publicRoot, 'index.html');
    return path.join(publicRoot, pathname.replace(/^\//u, ''), 'index.html');
}

function xmlEscape(value) {
    return String(value)
        .replaceAll('&', '&amp;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('"', '&quot;')
        .replaceAll("'", '&apos;');
}

function buildSitemap() {
    const entries = [];
    for (const pageType of pageTypes) {
        for (const localeKey of localeKeys) {
            const pathname = ROUTES[pageType][localeKey];
            const alternates = localeKeys.map((key) => `    <xhtml:link rel="alternate" hreflang="${LOCALES[key].hreflang}" href="${xmlEscape(`${SITE.domain}${ROUTES[pageType][key]}`)}"/>`).join('\n');
            entries.push(`  <url>
    <loc>${xmlEscape(`${SITE.domain}${pathname}`)}</loc>
    <lastmod>${SITE.lastModified}</lastmod>
${alternates}
    <xhtml:link rel="alternate" hreflang="x-default" href="${xmlEscape(`${SITE.domain}${ROUTES[pageType].ru}`)}"/>
  </url>`);
        }
    }
    return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${entries.join('\n')}
</urlset>
`;
}

function buildRedirects() {
    const lines = new Set(['/index / 301', '/index.html / 301']);
    for (const pageType of pageTypes) {
        for (const localeKey of localeKeys) {
            const canonical = ROUTES[pageType][localeKey];
            if (canonical === '/') continue;
            const withoutSlash = canonical.slice(0, -1);
            lines.add(`${withoutSlash} ${canonical} 301`);
            lines.add(`${withoutSlash}.html ${canonical} 301`);
            lines.add(`${withoutSlash}/index ${canonical} 301`);
            lines.add(`${withoutSlash}/index.html ${canonical} 301`);
        }
    }
    return `${[...lines].join('\n')}\n`;
}

function cspHash(text) {
    return `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;
}

function buildHeaders(schemaTexts) {
    const hashes = [...new Set(schemaTexts.map(cspHash))].sort().join(' ');
    const csp = [
        "default-src 'self'",
        `script-src 'self' ${hashes}`,
        "script-src-attr 'none'",
        "style-src 'self' https://fonts.googleapis.com",
        "font-src https://fonts.gstatic.com",
        "img-src 'self' data: blob:",
        "media-src 'self'",
        "connect-src 'self'",
        "object-src 'none'",
        "base-uri 'self'",
        "form-action 'self'",
        "frame-ancestors 'none'",
        'upgrade-insecure-requests'
    ].join('; ');
    if (csp.length > 2_000) throw new Error(`CSP is too long: ${csp.length} characters`);

    return `/*
  Content-Security-Policy: ${csp}
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin
  Permissions-Policy: camera=(), geolocation=(), microphone=(), payment=(), usb=()
  Referrer-Policy: strict-origin-when-cross-origin
  Strict-Transport-Security: max-age=63072000; includeSubDomains; preload
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY

/*.html
  Cache-Control: public, max-age=0, must-revalidate

/*.css
  Cache-Control: public, max-age=3600, stale-while-revalidate=86400

/*.js
  Cache-Control: public, max-age=3600, stale-while-revalidate=86400

/assets/*
  Cache-Control: public, max-age=86400, stale-while-revalidate=604800

/sitemap.xml
  Cache-Control: public, max-age=3600

/robots.txt
  Cache-Control: public, max-age=3600

/send
  Cache-Control: no-store

/health
  Cache-Control: no-store
  X-Robots-Tag: noindex, nofollow

https://:version.:subdomain.workers.dev/*
  X-Robots-Tag: noindex, nofollow
`;
}

function buildRobots() {
    return `User-agent: *
Allow: /
Disallow: /send
Disallow: /health

Sitemap: ${SITE.domain}/sitemap.xml
`;
}

function buildClientLocales() {
    const clientLocales = Object.fromEntries(localeKeys.map((localeKey) => [localeKey, {
        intlLocale: LOCALES[localeKey].intlLocale,
        calculator: LOCALES[localeKey].calculator
    }]));
    return `// Generated by scripts/build-site.mjs. Edit site/content.mjs instead.\nexport const CLIENT_LOCALES = Object.freeze(${JSON.stringify(clientLocales)});\n`;
}

