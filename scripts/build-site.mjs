function validatePage(html, localeKey, pageType) {
    const canonical = `${SITE.domain}${ROUTES[pageType][localeKey]}`;
    const h1Count = (html.match(/<h1(?:\s|>)/gu) || []).length;
    if (h1Count !== 1) throw new Error(`${localeKey}/${pageType}: expected one H1, found ${h1Count}`);
    if (!html.includes(`<html lang="${LOCALES[localeKey].htmlLang}">`)) throw new Error(`${localeKey}/${pageType}: wrong lang`);
    if (!html.includes(`<link rel="canonical" href="${canonical}">`)) throw new Error(`${localeKey}/${pageType}: wrong canonical`);
    for (const key of localeKeys) {
        const expected = `<link rel="alternate" hreflang="${LOCALES[key].hreflang}" href="${SITE.domain}${ROUTES[pageType][key]}">`;
        if (!html.includes(expected)) throw new Error(`${localeKey}/${pageType}: missing ${key} alternate`);
    }
    if (/\s(?:onclick|onload|onerror)=/iu.test(html)) throw new Error(`${localeKey}/${pageType}: inline handler found`);
    if (/\sstyle=/iu.test(html)) throw new Error(`${localeKey}/${pageType}: inline style found`);
    const ids = [...html.matchAll(/\sid="([^"]+)"/gu)].map((match) => match[1]);
    if (new Set(ids).size !== ids.length) throw new Error(`${localeKey}/${pageType}: duplicate id found`);
    for (const [, fragment] of html.matchAll(/href="#([^"]+)"/gu)) {
        if (!ids.includes(fragment)) throw new Error(`${localeKey}/${pageType}: missing fragment target #${fragment}`);
    }
    const schemaMatch = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/u);
    if (!schemaMatch) throw new Error(`${localeKey}/${pageType}: JSON-LD missing`);
    JSON.parse(schemaMatch[1]);
}

function expectedFiles() {
    const files = new Map();
    const schemaTexts = [];
    for (const pageType of pageTypes) {
        for (const localeKey of localeKeys) {
            if (!PAGES[localeKey]?.[pageType]) throw new Error(`Missing page content: ${localeKey}/${pageType}`);
            const { html, schemaText } = renderPage(localeKey, pageType);
            validatePage(html, localeKey, pageType);
            files.set(outputPath(ROUTES[pageType][localeKey]), html);
            schemaTexts.push(schemaText);
        }
    }
    files.set(path.join(publicRoot, 'sitemap.xml'), buildSitemap());
    files.set(path.join(publicRoot, 'robots.txt'), buildRobots());
    files.set(path.join(publicRoot, 'i18n.js'), buildClientLocales());
    files.set(path.join(publicRoot, '_redirects'), buildRedirects());
    files.set(path.join(publicRoot, '_headers'), buildHeaders(schemaTexts));
    files.set(path.join(publicRoot, '404.html'), build404());
    return files;
}

async function previousGeneratedPages() {
    const sitemap = await readFile(path.join(publicRoot, 'sitemap.xml'), 'utf8').catch(() => null);
    if (!sitemap) return new Map();

    const siteOrigin = new URL(SITE.domain).origin;
    const pages = new Map();
    for (const match of sitemap.matchAll(/<loc>(.*?)<\/loc>/gu)) {
        let url;
        try {
            url = new URL(match[1]);
        } catch {
            continue;
        }
        if (url.origin !== siteOrigin || url.search || url.hash || !url.pathname.endsWith('/')) continue;

        const filename = outputPath(url.pathname);
        const relative = path.relative(publicRoot, filename);
        if (relative.startsWith('..') || path.isAbsolute(relative)) continue;
        pages.set(filename, url.href);
    }
    return pages;
}

async function isGeneratedPage(filename, canonical) {
    const html = await readFile(filename, 'utf8').catch(() => null);
    return html?.includes(`<link rel="canonical" href="${canonical}">`) ?? false;
}

async function run() {
    // The previous generated sitemap acts as a route manifest. This lets us remove
    // only pages that this generator previously owned, without touching assets or
    // unrelated HTML that a user may have placed in public/.
    const previousPages = await previousGeneratedPages();
    const files = expectedFiles();
    const expectedPages = new Set(pageTypes.flatMap((pageType) =>
        localeKeys.map((localeKey) => outputPath(ROUTES[pageType][localeKey]))
    ));
    const stale = [];

    for (const [filename, canonical] of previousPages) {
        if (expectedPages.has(filename) || !(await isGeneratedPage(filename, canonical))) continue;
        if (checkOnly) {
            stale.push(path.relative(projectRoot, filename));
        } else {
            await unlink(filename);
        }
    }

    for (const [filename, content] of files) {
        if (checkOnly) {
            const existing = await readFile(filename, 'utf8').catch(() => null);
            if (existing !== content) stale.push(path.relative(projectRoot, filename));
            continue;
        }
        await mkdir(path.dirname(filename), { recursive: true });
        await writeFile(filename, content, 'utf8');
    }
    if (stale.length) throw new Error(`Generated site is stale:\n${stale.join('\n')}`);
    const mode = checkOnly ? 'verified' : 'generated';
    console.log(`Site ${mode}: ${pageTypes.length * localeKeys.length} pages, ${files.size} output files.`);
}

await run();
